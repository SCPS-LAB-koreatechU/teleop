"""Watch a motor across power cycles and say what the bus is actually doing.

For the case where the GUI shows a joint connecting and dropping again every
time the motor is power-cycled. Once a second it reports two independent facts:

  POWER   Is anything acknowledging our frames? Acknowledgement is generated by
          CAN hardware in every node that receives a frame, so it tracks whether
          a board is powered, regardless of its firmware. No ACK also blocks the
          transmit queue, which is why this tool has to survive ENOBUFS.
  DEVICE  Does the device answer the recoil protocol, and what does it report
          (bus voltage, error register, mode, position)?

The combination is the diagnosis:

  no ACK              -> the board is unpowered (or the bus is unplugged)
  ACK, never answers  -> powered, but the firmware is not running or is hung
  answers then quiet  -> look at the last voltage and error code it reported:
                         a sagging voltage is a supply problem, a non-zero error
                         is firmware, neither is a hang or a reset loop

Read-only: it never enables an output or changes a mode.

    ./boot_watch.py                       # can0, device 1
    ./boot_watch.py --ids 1 3 5 --seconds 300
"""

from __future__ import annotations

import argparse
import sys
import threading
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "source/berkeley_humanoid_lite_lowlevel"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from can_util import can_state, state_hint, transient, usable  # noqa: E402

PARAM = {"error": (0x014, "u32"), "mode": (0x010, "u32"),
         "volts": (0x100, "f32"), "pos": (0x060, "f32")}


CAN_ERR_ACK = 0x20


class AckWatcher(threading.Thread):
    """Counts no-acknowledgement error frames, which mean nobody is listening."""

    def __init__(self, channel: str):
        super().__init__(daemon=True)
        self.channel = channel
        self.stop = threading.Event()
        self.noack = 0
        self.last_noack = 0.0
        self.device_frames = 0
        self.failed: str | None = None

    def run(self):
        import can
        try:
            bus = can.interface.Bus(channel=self.channel, interface="socketcan",
                                    receive_own_messages=False)
        except Exception as e:  # noqa: BLE001
            self.failed = str(e)
            return
        try:
            while not self.stop.is_set():
                try:
                    m = bus.recv(timeout=0.2)
                except Exception as e:  # noqa: BLE001 - link taken down under us
                    self.failed = str(e)
                    return
                if m is None:
                    continue
                if m.is_error_frame:
                    if m.arbitration_id & CAN_ERR_ACK:
                        self.noack += 1
                        self.last_noack = time.monotonic()
                elif ((m.arbitration_id >> 7) & 0xF) in (1, 5, 7, 11, 14):
                    self.device_frames += 1
        finally:
            bus.shutdown()

    def powered(self, window: float = 1.5) -> bool | None:
        """True if nothing complained recently, False if frames go unacknowledged."""
        if self.noack == 0:
            return True
        return (time.monotonic() - self.last_noack) > window


class Link:
    """recoil bus calls that survive a blocked transmit queue."""

    def __init__(self, channel: str):
        import berkeley_humanoid_lite_lowlevel.recoil as recoil
        self.bus = recoil.Bus(channel=channel, bitrate=1000000)
        self.blocked = False
        self.sent = 0          # frames that actually left the controller

    def ping(self, dev: int, timeout: float) -> bool:
        try:
            ok = bool(self.bus.ping(dev, timeout=timeout))
            self.blocked = False
            self.sent += 1
            return ok
        except Exception as e:  # noqa: BLE001
            if not transient(e):
                raise
            self.blocked = True
            time.sleep(0.2)
            return False

    def read(self, dev: int, name: str, timeout: float):
        pid, kind = PARAM[name]
        fn = self.bus._read_parameter_u32 if kind == "u32" else self.bus._read_parameter_f32
        try:
            value = fn(dev, pid, timeout=timeout)
            self.blocked = False
            return value
        except Exception as e:  # noqa: BLE001
            if not transient(e):
                raise
            self.blocked = True
            time.sleep(0.2)
            return None

    def stop(self):
        try:
            self.bus.stop()
        except Exception:
            pass


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-c", "--channel", default="can0")
    ap.add_argument("--ids", type=int, nargs="+", default=[1])
    ap.add_argument("--seconds", type=float, default=240.0)
    ap.add_argument("--timeout", type=float, default=0.03, help="per-request timeout [s]")
    opts = ap.parse_args(argv)

    ok, why = usable(opts.channel)
    if not ok:
        print(why)
        return 2
    ack = AckWatcher(opts.channel)
    ack.start()
    link = Link(opts.channel)
    print(f"watching {opts.channel}, device(s) {opts.ids} - power-cycle the motor now.")
    print("one line per second; 'power' is whether anything acknowledges our frames.\n")
    start = can_state(opts.channel)
    print(f"  {opts.channel}: state {start.get('state', '?')}, restart-ms {start.get('restart_ms', '?')}, "
          f"error-passive transitions so far: {start.get('error_pass', '?')}")
    hint = state_hint(start, opts.channel)
    if hint:
        print(f"  NOTE: {hint}")
    print()
    print(f"{'time':>8}  {'bus':<26}  device")

    deadline = time.monotonic() + opts.seconds
    history: list[tuple[float, int, dict]] = []
    was_answering: dict[int, bool] = {d: False for d in opts.ids}
    windows = 0
    try:
        while time.monotonic() < deadline:
            line_time = time.strftime("%H:%M:%S")
            powered = ack.powered()
            answering = {}
            for dev in opts.ids:
                if not link.ping(dev, opts.timeout):
                    answering[dev] = None
                    continue
                row = {name: link.read(dev, name, opts.timeout) for name in PARAM}
                answering[dev] = row
                history.append((time.monotonic(), dev, row))

            info = can_state(opts.channel)
            state = info.get("state", "?")
            if link.blocked:
                power_text = f"{state}, queue blocked"
            elif powered is False:
                power_text = f"{state}, no ACK"
            else:
                power_text = state
            parts = []
            for dev, row in answering.items():
                if row is None:
                    parts.append(f"{dev}: silent")
                    if was_answering[dev]:
                        windows += 1
                    was_answering[dev] = False
                else:
                    v = f"{row['volts']:.1f}V" if row["volts"] is not None else "?V"
                    e = hex(row["error"]) if row["error"] is not None else "?"
                    m = hex(row["mode"]) if row["mode"] is not None else "?"
                    p = f"{row['pos']:+.3f}" if row["pos"] is not None else "?"
                    parts.append(f"{dev}: ANSWERING {v} err {e} mode {m} pos {p}")
                    was_answering[dev] = True
            print(f"{line_time}  {power_text:<22}  {'   '.join(parts)}", flush=True)
            time.sleep(0.6)
    except KeyboardInterrupt:
        pass
    finally:
        link.stop()
        ack.stop.set()
        ack.join(timeout=2)

    print("\n=== summary")
    end = can_state(opts.channel)
    print(f"  controller: {start.get('state','?')} -> {end.get('state','?')}   "
          f"error-passive transitions {start.get('error_pass','?')} -> {end.get('error_pass','?')}   "
          f"bus-off {end.get('bus_off','?')}")
    print(f"  no-ACK error frames: {ack.noack}   device-originated frames: {ack.device_frames}")
    hint = state_hint(end, opts.channel)
    if hint:
        print(f"  NOTE: {hint}")
    answered = [h for h in history if h[2]["pos"] is not None or h[2]["volts"] is not None]
    if not answered:
        if link.sent == 0:
            print("  Nothing was ever transmitted, so this says nothing about the motor.")
            print(f"  The bus was unusable the whole time (controller {end.get('state','?')}).")
        elif ack.noack:
            print("  The motor never answered and frames went unacknowledged for part of the time:")
            print("  that is a power or wiring problem, not the GUI. Check the board's LED,")
            print("  the supply, and the CAN connector.")
        else:
            print(f"  The motor never answered, and the {link.sent} frame(s) we did send were")
            print("  acknowledged: a board is powered with its CAN hardware up, but its")
            print("  firmware is not responding.")
        return 1
    volts = [h[2]["volts"] for h in answered if h[2]["volts"] is not None]
    errors = sorted({h[2]["error"] for h in answered if h[2]["error"] is not None})
    print(f"  it answered {len(answered)} time(s), dropping out {windows} time(s)")
    if volts:
        print(f"  bus voltage: min {min(volts):.2f} V  max {max(volts):.2f} V  last {volts[-1]:.2f} V")
    print(f"  error codes: {[hex(e) for e in errors] or 'none'}")
    if volts and min(volts) < 0.9 * max(volts):
        print("  verdict: the supply sagged while it was running - power, not firmware.")
    elif any(errors):
        print("  verdict: the firmware reported an error; decode it against recoil's ErrorCode.")
    elif windows:
        print("  verdict: it answered and then went quiet with healthy voltage and no error -")
        print("           the board is resetting or hanging after boot.")
    else:
        print("  verdict: it stayed up for the whole window.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
